"""Read-only V13 discrepancy triage: identify original ledger rows, never repair trades.

This tool is intentionally diagnostic. The raw field is generated by the paper
engine and is NOT independent exchange execution evidence.
"""
from __future__ import annotations

import hashlib
import json
import math
from collections import Counter, defaultdict
from decimal import Decimal, InvalidOperation, ROUND_HALF_EVEN
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
LEDGER = ROOT / "reports/paper_v13_ledger.json"


def decimal_or_none(value):
    try:
        d = Decimal(str(value))
        return d if d.is_finite() else None
    except (InvalidOperation, TypeError, ValueError):
        return None


def triage(ledger):
    groups = Counter()
    by_symbol = defaultdict(Counter)
    examples = []
    for di, decision in enumerate(ledger.get("decisions", [])):
        for ai, row in enumerate(decision.get("adjustments", [])):
            shown = decimal_or_none(row.get("order_value_brl"))
            raw = decimal_or_none(row.get("order_value_brl_unrounded"))
            if shown is None or shown < 0:
                category = "invalid_display"
            elif raw is None:
                category = "missing_raw"
            elif raw <= 0:
                category = "invalid_raw"
            elif raw.quantize(Decimal("0.01"), rounding=ROUND_HALF_EVEN) != shown:
                category = "mismatch"
            elif shown == 0:
                category = "subcent_simulated_notional"
            else:
                category = "matched"
            groups[category] += 1
            symbol = str(row.get("symbol", "UNKNOWN"))
            by_symbol[symbol][category] += 1
            if category not in ("matched",) and len(examples) < 40:
                serialized = json.dumps(row, sort_keys=True, ensure_ascii=False, separators=(",", ":"))
                examples.append({
                    "decision_index": di, "adjustment_index": ai,
                    "symbol": symbol,
                    "decision_timestamp": decision.get("timestamp"),
                    "row_sha256": hashlib.sha256(serialized.encode()).hexdigest(),
                    "shown": str(shown) if shown is not None else None,
                    "raw": str(raw) if raw is not None else None,
                    "difference_brl": str(shown - raw) if shown is not None and raw is not None else None,
                    "classification": category,
                })
    return {
        "ledger_sha256": hashlib.sha256(LEDGER.read_bytes()).hexdigest() if LEDGER.exists() else None,
        "counts": dict(groups),
        "by_symbol": {k: dict(v) for k, v in sorted(by_symbol.items())},
        "first_40_nonmatched": examples,
        "warning": "Generated raw notional is not an independent exchange fill or FX receipt.",
    }


def main():
    result = triage(json.loads(LEDGER.read_text(encoding="utf-8")))
    print(json.dumps(result, indent=2, ensure_ascii=False))
    if any(result["counts"].get(k, 0) for k in ("invalid_display", "missing_raw", "invalid_raw", "mismatch")):
        raise SystemExit(2)


if __name__ == "__main__":
    main()
