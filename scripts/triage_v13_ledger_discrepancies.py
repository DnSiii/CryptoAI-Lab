"""Read-only V13 discrepancy triage: identify original ledger rows, never repair trades.

This tool is intentionally diagnostic. The raw field is generated by the paper
engine and is NOT independent exchange execution evidence.
"""
from __future__ import annotations

import hashlib
import json
import math
from collections import Counter, defaultdict
from decimal import Decimal, InvalidOperation, ROUND_HALF_EVEN
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
LEDGER = ROOT / "reports/paper_v13_ledger.json"


def decimal_or_none(value):
    try:
        d = Decimal(str(value))
        return d if d.is_finite() else None
    except (InvalidOperation, TypeError, ValueError):
        return None


def triage(ledger, source_bytes=None):
    groups = Counter()
    missing_raw_by_symbol = Counter()
    mismatch_over_cent_by_symbol = Counter()
    by_symbol = defaultdict(Counter)
    examples_by_category = defaultdict(list)
    max_abs_difference_by_symbol = {}
    mismatch_manifest = []
    missing_raw_manifest = []
    for di, decision in enumerate(ledger.get("decisions", [])):
        for ai, row in enumerate(decision.get("adjustments", [])):
            shown = decimal_or_none(row.get("order_value_brl"))
            raw = decimal_or_none(row.get("order_value_brl_unrounded"))
            if shown is None or shown < 0:
                category = "invalid_display"
            elif raw is None:
                category = "missing_raw"
            elif raw <= 0:
                category = "invalid_raw"
            elif raw.quantize(Decimal("0.01"), rounding=ROUND_HALF_EVEN) != shown:
                category = "mismatch"
            elif shown == 0:
                category = "subcent_simulated_notional"
            else:
                category = "matched"
            groups[category] += 1
            if category == "missing_raw":
                missing_raw_by_symbol[str(row.get("symbol", "UNKNOWN"))] += 1
            if category == "mismatch" and abs(shown - raw) > Decimal("0.01"):
                mismatch_over_cent_by_symbol[str(row.get("symbol", "UNKNOWN"))] += 1
            symbol = str(row.get("symbol", "UNKNOWN"))
            by_symbol[symbol][category] += 1
            if category not in ("matched",) and len(examples_by_category[category]) < 10:
                serialized = json.dumps(row, sort_keys=True, ensure_ascii=False, separators=(",", ":"))
                examples_by_category[category].append({
                    "decision_index": di, "adjustment_index": ai,
                    "symbol": symbol,
                    "decision_timestamp": decision.get("timestamp"),
                    "row_sha256": hashlib.sha256(serialized.encode()).hexdigest(),
                    "shown": str(shown) if shown is not None else None,
                    "raw": str(raw) if raw is not None else None,
                    "difference_brl": str(shown - raw) if shown is not None and raw is not None else None,
                    "classification": category,
                })
            if category == "missing_raw":
                missing_raw_manifest.append({
                    "decision_index": di, "adjustment_index": ai,
                    "symbol": symbol, "decision_timestamp": decision.get("timestamp"),
                    "row_sha256": hashlib.sha256(json.dumps(row, sort_keys=True, ensure_ascii=False, separators=(",", ":")).encode()).hexdigest(),
                    "shown": str(shown) if shown is not None else None,
                    "raw": None,
                })
            if category == "mismatch":
                mismatch_manifest.append({
                    "decision_index": di, "adjustment_index": ai,
                    "symbol": symbol, "decision_timestamp": decision.get("timestamp"),
                    "row_sha256": hashlib.sha256(json.dumps(row, sort_keys=True, ensure_ascii=False, separators=(",", ":")).encode()).hexdigest(),
                    "shown": str(shown), "raw": str(raw),
                    "difference_brl": str(shown - raw),
                })
                difference = abs(shown - raw)
                max_abs_difference_by_symbol[symbol] = max(difference, max_abs_difference_by_symbol.get(symbol, Decimal("0")))
    return {
        "max_abs_mismatch_brl_by_symbol": {k: str(v) for k, v in sorted(max_abs_difference_by_symbol.items())},
        "ledger_sha256": hashlib.sha256(source_bytes).hexdigest() if source_bytes is not None else None,
        "missing_raw_by_symbol": dict(sorted(missing_raw_by_symbol.items())),
        "mismatch_over_one_cent_by_symbol": dict(sorted(mismatch_over_cent_by_symbol.items())),
        "counts": dict(groups),
        "mismatch_manifest": mismatch_manifest,
        "missing_raw_manifest": missing_raw_manifest,
        "by_symbol": {k: dict(v) for k, v in sorted(by_symbol.items())},
        "examples_by_category": dict(examples_by_category),
        "warning": "Generated raw notional is not an independent exchange fill or FX receipt.",
    }


def main():
    source_bytes = LEDGER.read_bytes()
    result = triage(json.loads(source_bytes.decode("utf-8")), source_bytes=source_bytes)
    print(json.dumps(result, indent=2, ensure_ascii=False))
    if any(result["counts"].get(k, 0) for k in ("invalid_display", "missing_raw", "invalid_raw", "mismatch")):
        raise SystemExit(2)


if __name__ == "__main__":
    main()
